#!/usr/bin/env python3
"""Pack baked gravel-plane sprites into hopper_gravel tileset + Lua cell table.

Run after bake_gravel_planes.py:
  python3 pack_gravel_planes.py
"""

from __future__ import annotations

import os
import struct
import subprocess
import sys

from PIL import Image

import pz_iso

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "../../Contents/mods/DumpTruckGravelMod/42.20"))
SRC_DIR = os.path.join(HERE, "gravel_tiles")
MANIFEST = os.path.join(SRC_DIR, "manifest.txt")
OUT_SRC = os.path.join(REPO, "media/texturepacks_src/hopper_gravel")
PACK_PATH = os.path.join(REPO, "media/texturepacks/DumpTruckGravelMod.pack")
TILES_PATH = os.path.join(REPO, "media/hopper_gravel.tiles")
LUA_PATH = os.path.join(REPO, "media/lua/shared/DumpTruck/LoadingHopperGravelCells.lua")
PZ_PACK = os.path.normpath(
    os.path.join(HERE, "../../../../reference/pz-pack/target/release/pz-pack-tool")
)

MIN_OPAQUE = 8
PLANE_ORDER = ("hi", "mid", "lo", "vlo")


def opaque_count(im: Image.Image) -> int:
    return sum(1 for px in im.getdata() if px[3] > 8)


def read_manifest():
    """Return list of (plane, frame, gx, gy, fz, filename)."""
    rows = []
    with open(MANIFEST, encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) != 6:
                continue
            plane, frame, gx, gy, fz, name = parts
            src = os.path.join(SRC_DIR, name)
            if not os.path.isfile(src):
                continue
            im = Image.open(src).convert("RGBA")
            if opaque_count(im) < MIN_OPAQUE:
                continue
            rows.append((plane, int(frame), int(gx), int(gy), int(fz), name))
    rows.sort(
        key=lambda r: (PLANE_ORDER.index(r[0]) if r[0] in PLANE_ORDER else 9, r[1], r[3], r[2])
    )
    print("manifest keep", len(rows))
    return rows


def harden_alpha(im: Image.Image) -> Image.Image:
    px = im.load()
    w, h = im.size
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            px[x, y] = (r, g, b, 255 if a >= 128 else 0)
    return im


def write_tomls(n: int):
    for i in range(n):
        stem = "hopper_gravel_%d" % i
        with open(os.path.join(OUT_SRC, stem + ".toml"), "w", encoding="utf-8") as handle:
            handle.write("[%s]\n" % stem)
            handle.write("pos = [0, 0]\n")
            handle.write("size = [%d, %d]\n" % (pz_iso.TILE_W, pz_iso.TILE_H))


def write_tiles(n: int):
    def s(text):
        return text.encode("utf-8") + b"\n"

    body = bytearray()
    body += s("hopper_gravel")
    body += s("hopper_gravel")
    cols = 8
    rows = max(1, (n + cols - 1) // cols)
    body += struct.pack("<iiii", cols, rows, 1, n)
    for i in range(n):
        props = [("ForceAmbient", ""), ("NeverCutaway", "")]
        if i == 0:
            props.append(("CustomName", "Hopper Gravel"))
        body += struct.pack("<i", len(props))
        for key, val in props:
            body += s(key)
            body += s(val)
    out = bytearray()
    out += b"tdef"
    out += struct.pack("<ii", 1, 1)
    out += body
    with open(TILES_PATH, "wb") as handle:
        handle.write(out)


def write_lua(rows):
    """Group by plane → list of {gx, gy, fz, frames=[sprite...]}."""
    by_cell = {}
    for i, (plane, frame, gx, gy, fz, _name) in enumerate(rows):
        key = (plane, gx, gy, fz)
        by_cell.setdefault(key, []).append((frame, i))

    planes = {}
    for (plane, gx, gy, fz), frames in sorted(
        by_cell.items(),
        key=lambda kv: (
            PLANE_ORDER.index(kv[0][0]) if kv[0][0] in PLANE_ORDER else 9,
            kv[0][2],
            kv[0][1],
        ),
    ):
        frames.sort(key=lambda t: t[0])
        sprite_names = []
        expected = 0
        for frame, idx in frames:
            while expected < frame:
                sprite_names.append(sprite_names[-1] if sprite_names else "hopper_gravel_%d" % idx)
                expected += 1
            sprite_names.append("hopper_gravel_%d" % idx)
            expected = frame + 1
        planes.setdefault(plane, []).append(
            {"gx": gx, "gy": gy, "fz": fz, "frames": sprite_names}
        )

    lines = [
        "-- Generated by pack_gravel_planes.py — do not edit by hand.",
        "return {",
    ]
    for plane in PLANE_ORDER:
        cells = planes.get(plane, [])
        lines.append("    %s = {" % plane)
        for c in cells:
            frame_lit = ", ".join('"%s"' % s for s in c["frames"])
            lines.append(
                "        { gx = %d, gy = %d, fz = %d, frames = { %s } },"
                % (c["gx"], c["gy"], c["fz"], frame_lit)
            )
        lines.append("    },")
    lines.append("}")
    lines.append("")
    with open(LUA_PATH, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print("wrote", LUA_PATH)


def merge_pack():
    if not os.path.isfile(PZ_PACK):
        raise RuntimeError("pz-pack-tool missing at %s — cargo build --release" % PZ_PACK)
    work = os.path.join(HERE, "_pack_work_gravel")
    if os.path.isdir(work):
        for root, _dirs, files in os.walk(work, topdown=False):
            for name in files:
                os.remove(os.path.join(root, name))
            for name in _dirs:
                os.rmdir(os.path.join(root, name))
        os.rmdir(work)
    os.makedirs(work, exist_ok=True)
    if os.path.isfile(PACK_PATH):
        subprocess.check_call([PZ_PACK, "unpack", PACK_PATH, work])
    for name in list(os.listdir(work)):
        if name.startswith("hopper_gravel_"):
            os.remove(os.path.join(work, name))
    for name in os.listdir(OUT_SRC):
        src = os.path.join(OUT_SRC, name)
        dst = os.path.join(work, name)
        with open(src, "rb") as rh, open(dst, "wb") as wh:
            wh.write(rh.read())
    tmp_pack = PACK_PATH + ".tmp"
    subprocess.check_call([PZ_PACK, "pack", work, tmp_pack])
    os.replace(tmp_pack, PACK_PATH)
    print("wrote", PACK_PATH)


def ensure_mod_info_tiledef():
    path = os.path.join(REPO, "mod.info")
    with open(path, encoding="utf-8") as handle:
        text = handle.read()
    if "tiledef=hopper_gravel" not in text:
        if not text.endswith("\n"):
            text += "\n"
        text += "tiledef=hopper_gravel 4733\n"
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(text)
        print("added tiledef=hopper_gravel 4733 to mod.info")


def main():
    if not os.path.isfile(MANIFEST):
        print("missing", MANIFEST, file=sys.stderr)
        sys.exit(1)
    rows = read_manifest()
    if not rows:
        print("empty manifest", file=sys.stderr)
        sys.exit(1)
    os.makedirs(OUT_SRC, exist_ok=True)
    for name in os.listdir(OUT_SRC):
        os.remove(os.path.join(OUT_SRC, name))

    for i, (_plane, _frame, gx, gy, fz, name) in enumerate(rows):
        src = os.path.join(SRC_DIR, name)
        im = Image.open(src).convert("RGBA")
        if im.size != (pz_iso.TILE_W, pz_iso.TILE_H):
            canvas = Image.new("RGBA", (pz_iso.TILE_W, pz_iso.TILE_H), (0, 0, 0, 0))
            canvas.paste(im, (0, 0), im)
            im = canvas
        im = harden_alpha(im)
        dst = os.path.join(OUT_SRC, "hopper_gravel_%d.png" % i)
        im.save(dst)
        print("pack", i, name, "gx", gx, "gy", gy, "fz", fz, "opq", opaque_count(im))

    write_tomls(len(rows))
    write_tiles(len(rows))
    write_lua(rows)
    ensure_mod_info_tiledef()
    merge_pack()
    print("pack_gravel_planes done", len(rows), "sprites")


if __name__ == "__main__":
    main()
